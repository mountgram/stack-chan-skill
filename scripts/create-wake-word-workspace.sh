write_file "$scripts_dir/generate_features.py" <<'EOF'
#!/usr/bin/env python3
from pathlib import Path

from mmap_ninja.ragged import RaggedMmap
from microwakeword.audio.augmentation import Augmentation
from microwakeword.audio.clips import Clips
from microwakeword.audio.spectrograms import SpectrogramGeneration

clips = Clips(
    input_directory="generated_samples",
    file_pattern="*.wav",
    max_clip_duration_s=None,
    remove_silence=False,
    random_split_seed=10,
    split_count=0.1,
)

augmenter = Augmentation(
    augmentation_duration_s=3.2,
    augmentation_probabilities={
        "SevenBandParametricEQ": 0.1,
        "TanhDistortion": 0.1,
        "PitchShift": 0.1,
        "BandStopFilter": 0.1,
        "AddColorNoise": 0.1,
        "AddBackgroundNoise": 0.75,
        "Gain": 1.0,
        "RIR": 0.5,
    },
    impulse_paths=["mit_rirs"],
    background_paths=["fma_16k", "audioset_16k"],
    background_min_snr_db=-5,
    background_max_snr_db=10,
    min_jitter_s=0.195,
    max_jitter_s=0.205,
)

output_root = Path("generated_augmented_features")
output_root.mkdir(exist_ok=True)

for split in ("training", "validation", "testing"):
    split_name = "train"
    repetition = 2
    slide_frames = 10
    if split == "validation":
        split_name = "validation"
        repetition = 1
    elif split == "testing":
        split_name = "test"
        repetition = 1
        slide_frames = 1

    out_dir = output_root / split
    out_dir.mkdir(exist_ok=True)
    spectrograms = SpectrogramGeneration(
        clips=clips,
        augmenter=augmenter,
        slide_frames=slide_frames,
        step_ms=10,
    )
    RaggedMmap.from_generator(
        out_dir=str(out_dir / "wakeword_mmap"),
        sample_generator=spectrograms.spectrogram_generator(split=split_name, repeat=repetition),
        batch_size=100,
        verbose=True,
    )
EOF

write_file "$scripts_dir/download_backgrounds.py" <<'EOF'
#!/usr/bin/env python3
import tarfile
import urllib.request
import zipfile
from pathlib import Path

import datasets
import numpy as np
import scipy.io.wavfile
from tqdm import tqdm

def download(url: str, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        return
    print(f"download {url}")
    urllib.request.urlretrieve(url, path)

def write_wav(path: Path, sample_rate: int, audio: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    scipy.io.wavfile.write(path, sample_rate, (audio * 32767).astype(np.int16))

rir_dir = Path("mit_rirs")
if not rir_dir.exists():
    rir_dir.mkdir()
    rir_dataset = datasets.load_dataset(
        "davidscripka/MIT_environmental_impulse_responses",
        split="train",
        streaming=True,
    )
    for row in tqdm(rir_dataset, desc="MIT RIR"):
        name = Path(row["audio"]["path"]).name
        write_wav(rir_dir / name, 16000, row["audio"]["array"])

audioset_tar = Path("audioset/bal_train09.tar")
download(
    "https://huggingface.co/datasets/agkphysics/AudioSet/resolve/main/data/bal_train09.tar",
    audioset_tar,
)
audioset_audio_dir = Path("audioset/audio")
if not audioset_audio_dir.exists():
    with tarfile.open(audioset_tar) as tar:
        tar.extractall("audioset")

audioset_out = Path("audioset_16k")
if not audioset_out.exists():
    audioset_out.mkdir()
    audioset_dataset = datasets.Dataset.from_dict(
        {"audio": [str(i) for i in audioset_audio_dir.glob("**/*.flac")]}
    )
    audioset_dataset = audioset_dataset.cast_column("audio", datasets.Audio(sampling_rate=16000))
    for row in tqdm(audioset_dataset, desc="AudioSet 16k"):
        name = Path(row["audio"]["path"]).with_suffix(".wav").name
        write_wav(audioset_out / name, 16000, row["audio"]["array"])

fma_zip = Path("fma/fma_xs.zip")
download("https://huggingface.co/datasets/mchl914/fma_xsmall/resolve/main/fma_xs.zip", fma_zip)
fma_audio_dir = Path("fma/fma_small")
if not fma_audio_dir.exists():
    with zipfile.ZipFile(fma_zip) as zf:
        zf.extractall("fma")

fma_out = Path("fma_16k")
if not fma_out.exists():
    fma_out.mkdir()
    fma_dataset = datasets.Dataset.from_dict(
        {"audio": [str(i) for i in fma_audio_dir.glob("**/*.mp3")]}
    )
    fma_dataset = fma_dataset.cast_column("audio", datasets.Audio(sampling_rate=16000))
    for row in tqdm(fma_dataset, desc="FMA 16k"):
        name = Path(row["audio"]["path"]).with_suffix(".wav").name
        write_wav(fma_out / name, 16000, row["audio"]["array"])
EOF

write_file "$scripts_dir/write_manifest.py" <<'EOF'
#!/usr/bin/env python3
import json
import os
from pathlib import Path

phrase = os.environ["WAKE_WORD_PHRASE"]
model_id = os.environ["WAKE_WORD_MODEL_ID"]
author = os.environ.get("WAKE_WORD_AUTHOR", "StackChan")
cutoff = float(os.environ.get("WAKE_WORD_PROBABILITY_CUTOFF", "0.97"))
window = int(os.environ.get("WAKE_WORD_SLIDING_WINDOW_SIZE", "5"))
arena = int(os.environ.get("WAKE_WORD_TENSOR_ARENA_SIZE", "26080"))

model_path = Path("trained_models") / model_id / "tflite_stream_state_internal_quant" / "stream_state_internal_quant.tflite"
out_dir = Path("dist")
out_dir.mkdir(exist_ok=True)
tflite_out = out_dir / f"{model_id}.tflite"
manifest_out = out_dir / f"{model_id}.json"

if not model_path.exists():
    raise SystemExit(f"missing trained model: {model_path}")

tflite_out.write_bytes(model_path.read_bytes())
manifest = {
    "type": "micro",
    "wake_word": phrase,
    "author": author,
    "model": tflite_out.name,
    "trained_languages": ["en"],
    "version": 2,
    "micro": {
        "probability_cutoff": cutoff,
        "feature_step_size": 10,
        "sliding_window_size": window,
        "tensor_arena_size": arena,
        "minimum_esphome_version": "2024.7.0",
    },
}
manifest_out.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
print(manifest_out)
print(tflite_out)
EOF

write_file "$workspace/run.sh" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")"
source ./wake-word.env

cmd="${1:-help}"

install_python_deps() {
    python3 -m pip install --upgrade pip
    python3 -m pip install \
        "git+https://github.com/whatsnowplaying/audio-metadata@d4ebb238e6a401bb1a5aaaac60c9e2b3cb30929f" \
        datasets scipy numpy tqdm mmap_ninja pyyaml torch torchaudio piper-phonemize-cross==1.2.1
    if [[ "$(uname -s)" == "Darwin" ]]; then
        python3 -m pip install 'git+https://github.com/puddly/pymicro-features@puddly/minimum-cpp-version'
    fi
    if [[ ! -d microWakeWord ]]; then
        git clone https://github.com/OHF-Voice/micro-wake-word microWakeWord
    fi
    python3 -m pip install -e ./microWakeWord
    if [[ ! -d piper-sample-generator ]]; then
        if [[ "$(uname -s)" == "Darwin" ]]; then
            git clone -b mps-support https://github.com/kahrendt/piper-sample-generator
        else
            git clone https://github.com/rhasspy/piper-sample-generator
        fi
    fi
}

download_piper_model() {
    mkdir -p models
    if [[ ! -f "$PIPER_GENERATOR_MODEL" ]]; then
        curl -L "$PIPER_GENERATOR_MODEL_URL" -o "$PIPER_GENERATOR_MODEL"
    fi
    if [[ ! -f "$PIPER_GENERATOR_MODEL.json" ]]; then
        curl -L "$PIPER_GENERATOR_CONFIG_URL" -o "$PIPER_GENERATOR_MODEL.json"
    fi
}

piper_text_args() {
    if [[ -n "${WAKE_WORD_PHONEME:-}" ]]; then
        printf '%s\0%s\0' "$WAKE_WORD_PHONEME" "--phoneme-input"
    else
        printf '%s\0' "$WAKE_WORD_PHRASE"
    fi
}

generate_samples() {
    local count="$1"
    local out_dir="$2"
    download_piper_model
    local parts=()
    while IFS= read -r -d '' part; do
        parts+=("$part")
    done < <(piper_text_args)
    python3 piper-sample-generator/generate_samples.py "${parts[0]}" \
        --model "$PIPER_GENERATOR_MODEL" \
        --max-samples "$count" \
        --batch-size "$WAKE_WORD_BATCH_SIZE" \
        --length-scales $PIPER_LENGTH_SCALES \
        --noise-scales $PIPER_NOISE_SCALES \
        --noise-scale-ws $PIPER_NOISE_SCALE_WS \
        --slerp-weights $PIPER_SLERP_WEIGHTS \
        --output-dir "$out_dir" \
        "${parts[@]:1}"
}

case "$cmd" in
    help)
        cat <<USAGE
Usage: ./run.sh <command>

Commands:
  setup       Install Python deps and clone microWakeWord + Piper sample generator.
  preview     Generate one Piper sample in preview_samples/.
  generate    Generate positive wake-word samples in generated_samples/.
  backgrounds Download RIR/noise/music audio used for positive sample augmentation.
  features    Convert generated samples to augmented microWakeWord features.
  negatives   Download pre-generated negative feature datasets from Hugging Face.
  train       Train and quantize the microWakeWord model.
  manifest    Copy the trained .tflite and write dist/${WAKE_WORD_MODEL_ID}.json.

Run order:
  ./run.sh setup
  ./run.sh preview
  ./run.sh generate
  ./run.sh backgrounds
  ./run.sh negatives
  ./run.sh features
  ./run.sh train
  ./run.sh manifest
USAGE
        ;;
    setup)
        install_python_deps
        download_piper_model
        ;;
    preview)
        generate_samples 1 preview_samples
        ;;
    generate)
        generate_samples "$WAKE_WORD_SAMPLES" generated_samples
        ;;
    negatives)
        mkdir -p negative_datasets
        for fname in dinner_party.zip dinner_party_eval.zip no_speech.zip speech.zip; do
            curl -L "https://huggingface.co/datasets/kahrendt/microwakeword/resolve/main/$fname" -o "negative_datasets/$fname"
            unzip -qo "negative_datasets/$fname" -d negative_datasets
        done
        ;;
    backgrounds)
        python3 scripts/download_backgrounds.py
        ;;
    features)
        python3 scripts/generate_features.py
        ;;
    train)
        python3 -m microwakeword.model_train_eval \
            --training_config=training_parameters.yaml \
            --train 1 \
            --restore_checkpoint 1 \
            --test_tf_nonstreaming 0 \
            --test_tflite_nonstreaming 0 \
            --test_tflite_nonstreaming_quantized 0 \
            --test_tflite_streaming 0 \
            --test_tflite_streaming_quantized 1 \
            --use_weights best_weights \
            mixednet \
            --pointwise_filters "64,64,64,64" \
            --repeat_in_block "1, 1, 1, 1" \
            --mixconv_kernel_sizes "[5], [7,11], [9,15], [23]" \
            --residual_connection "0,0,0,0" \
            --first_conv_filters 32 \
            --first_conv_kernel_size 5 \
            --stride 3
        ;;
    manifest)
        python3 scripts/write_manifest.py
        ;;
    *)
        echo "unknown command: $cmd" >&2
        exit 1
        ;;
esac
EOF

