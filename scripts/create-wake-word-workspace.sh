#!/usr/bin/env bash
set -euo pipefail

usage() {
    cat <<'EOF'
Usage:
  scripts/create-wake-word-workspace.sh "Stacky" [options]

Creates a project-local microWakeWord training workspace with Piper sample
generation, feature generation, training config, model training command, and
ESPHome-style model manifest generation.

Options:
  --id ID                Model id/slug. Default: phrase lowercased with non-alnum as '-'.
  --phoneme TEXT         Piper phoneme input. Use when normal spelling sounds wrong.
  --project-root DIR     Project root for .stacky-wake-words output. Default: current directory.
  --samples N            Piper positive sample count. Default: 1000.
  --batch-size N         Piper batch size. Default: 100.
  --force                Overwrite generated control files if workspace already exists.
  -h, --help             Show this help.

Examples:
  scripts/create-wake-word-workspace.sh "Stacky"
  scripts/create-wake-word-workspace.sh "Hey Frank" --id hey-frank --phoneme "hˈeɪ fɹˈæŋk˺"
EOF
}

slugify() {
    printf '%s' "$1" \
        | tr '[:upper:]' '[:lower:]' \
        | sed -E 's/[^a-z0-9]+/-/g; s/^-+//; s/-+$//'
}

quote_sh() {
    printf "%q" "$1"
}

phrase=""
model_id=""
phoneme=""
project_root="$(pwd)"
samples="1000"
batch_size="100"
force="0"

while [[ $# -gt 0 ]]; do
    case "$1" in
        --id)
            model_id="${2:-}"
            shift 2
            ;;
        --phoneme)
            phoneme="${2:-}"
            shift 2
            ;;
        --project-root)
            project_root="${2:-}"
            shift 2
            ;;
        --samples)
            samples="${2:-}"
            shift 2
            ;;
        --batch-size)
            batch_size="${2:-}"
            shift 2
            ;;
        --force)
            force="1"
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        -*)
            echo "ERROR: unknown option: $1" >&2
            usage >&2
            exit 1
            ;;
        *)
            if [[ -n "$phrase" ]]; then
                echo "ERROR: phrase already set to '$phrase'" >&2
                exit 1
            fi
            phrase="$1"
            shift
            ;;
    esac
done

if [[ -z "$phrase" ]]; then
    usage >&2
    exit 1
fi

if [[ -z "$model_id" ]]; then
    model_id="$(slugify "$phrase")"
fi

if [[ -z "$model_id" ]]; then
    echo "ERROR: model id is empty after slugifying phrase" >&2
    exit 1
fi

if ! [[ "$samples" =~ ^[0-9]+$ ]] || [[ "$samples" -lt 1 ]]; then
    echo "ERROR: --samples must be a positive integer" >&2
    exit 1
fi

if ! [[ "$batch_size" =~ ^[0-9]+$ ]] || [[ "$batch_size" -lt 1 ]]; then
    echo "ERROR: --batch-size must be a positive integer" >&2
    exit 1
fi

workspace="$project_root/.stacky-wake-words/$model_id"
scripts_dir="$workspace/scripts"

mkdir -p "$scripts_dir"

write_file() {
    local path="$1"
    if [[ -e "$path" && "$force" != "1" ]]; then
        echo "keep $path (use --force to overwrite)"
        return
    fi
    cat > "$path"
}

phrase_q="$(quote_sh "$phrase")"
model_id_q="$(quote_sh "$model_id")"
phoneme_q="$(quote_sh "$phoneme")"

write_file "$workspace/wake-word.env" <<EOF
# Generated by stack-chan-skill/scripts/create-wake-word-workspace.sh
WAKE_WORD_PHRASE=$phrase_q
WAKE_WORD_MODEL_ID=$model_id_q
WAKE_WORD_PHONEME=$phoneme_q
WAKE_WORD_SAMPLES=$samples
WAKE_WORD_BATCH_SIZE=$batch_size

# Piper generator model used by OHF's basic microWakeWord notebook.
PIPER_GENERATOR_MODEL=models/en_US-libritts_r-medium.pt
PIPER_GENERATOR_MODEL_URL=https://github.com/rhasspy/piper-sample-generator/releases/download/v2.0.0/en_US-libritts_r-medium.pt
PIPER_GENERATOR_CONFIG_URL=https://github.com/rhasspy/piper-sample-generator/releases/download/v2.0.0/en_US-libritts_r-medium.pt.json

# Tuning knobs passed to piper-sample-generator.
PIPER_LENGTH_SCALES="1.0 0.75 1.25 1.4"
PIPER_NOISE_SCALES="0.667 0.75 0.85 0.9 1.0 1.4"
PIPER_NOISE_SCALE_WS="0.8"
PIPER_SLERP_WEIGHTS="0.5"

# Manifest defaults. Adjust after validation.
WAKE_WORD_PROBABILITY_CUTOFF=0.97
WAKE_WORD_SLIDING_WINDOW_SIZE=5
WAKE_WORD_TENSOR_ARENA_SIZE=26080
WAKE_WORD_AUTHOR=StackChan
EOF

